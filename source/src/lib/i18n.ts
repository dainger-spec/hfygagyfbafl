export type Msg = keyof typeof dict.ru;

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "ru" || value === "en";
}

export function detectLocale(): Locale {
  if (typeof window === "undefined") return "ru";
  try {
    const saved = window.localStorage.getItem("epb-locale");
    if (isLocale(saved)) return saved;
  } catch {
    /* ignore */
  }
  const lang =
    window.Telegram?.WebApp?.initDataUnsafe?.user?.language_code ||
    (typeof navigator !== "undefined" ? navigator.language : "") ||
    "";
  if (/^en/i.test(lang)) return "en";
  return "ru";
}

export function persistLocale(locale: Locale) {
  try {
    window.localStorage.setItem("epb-locale", locale);
  } catch {
    /* ignore */
  }
}

export function hasSavedLocale(): boolean {
  if (typeof window === "undefined") return false;
  try {
    return isLocale(window.localStorage.getItem("epb-locale"));
  } catch {
    return false;
  }
}

export function t(locale: Locale, key: Msg, vars?: Record<string, string | number>): string {
  let text: string = dict[locale][key] || dict.ru[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

