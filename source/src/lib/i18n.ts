export type BotMsg = keyof typeof botDict.ru;

export function tb(locale: Locale, key: BotMsg, vars?: Record<string, string | number>): string {
  let text: string = botDict[locale][key] || botDict.ru[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}
